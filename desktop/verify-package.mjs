import assert from 'node:assert/strict';
import { lstat, readFile, realpath } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { verifyThirdPartyNotices } from './third-party-notices.mjs';
import { sharedBuildInfo } from '../scripts/lib/build-info.mjs';
import { collectReleaseFiles, loadReleasePolicy } from '../scripts/lib/release-files.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const builderRequire = createRequire(require.resolve('electron-builder/package.json'));
const packagingRequire = createRequire(builderRequire.resolve('app-builder-lib/package.json'));
const asar = packagingRequire('@electron/asar');
const resedit = packagingRequire('resedit');
const { getCurrentFuseWire, FuseV1Options } = packagingRequire('@electron/fuses');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

// Only the reviewed built-in skill assets belong in a distributable archive.
// Custom project skills, private resources and arbitrary files are not allowed.
export const BUNDLED_SKILL_FILES = Object.freeze([
  'skills/README.md',
  'skills/general/SKILL.md',
  'skills/research/SKILL.md',
  'skills/writing/SKILL.md',
  'skills/code/SKILL.md',
  'skills/planning/SKILL.md',
  'skills/translation/SKILL.md',
  'skills/code/references/verification.md',
]);

export async function verifyBundledSkillResource(relative, bytes) {
  assert.ok(BUNDLED_SKILL_FILES.includes(relative), 'Unexpected bundled skill resource ' + relative);
  assert.equal(sha256(await readFile(path.join(root, relative))), sha256(bytes), 'Bundled skill differs from source ' + relative);
}


// Reconstruct the reviewed dist inputs from the same source policy as build.mjs,
// then apply only the existing literal files and four directory patterns. Never
// infer completeness from the archive being inspected or a mutable dist folder.
async function desktopArchiveInputs() {
  const policy = await loadReleasePolicy(root);
  const maintained = await collectReleaseFiles(root, policy);
  const config = JSON.parse(await readFile(path.join(root, 'desktop/electron-builder.json'), 'utf8'));
  assert.ok(Array.isArray(config.files), 'Revalidate changed desktop file configuration');
  const recursive = new Set(['core/**/*', 'server/**/*', 'public/**/*', 'skills/**/*']);
  for (const pattern of config.files) {
    assert.ok(typeof pattern === 'string' && (recursive.has(pattern) || /^[A-Za-z0-9_.-]+(?:\/[A-Za-z0-9_.-]+)*$/u.test(pattern))
      && !pattern.split('/').some(part => part === '.' || part === '..'), 'Revalidate unsupported desktop file pattern');
  }
  const selected = file => config.files.some(pattern => recursive.has(pattern) ? file.startsWith(pattern.slice(0, -4)) : file === pattern);
  const built = maintained.filter(file => !file.endsWith('.test.mjs') && (
    /^(?:core|server|public|desktop|skills)\//u.test(file) || ['LICENSE', 'NOTICE', 'README.md'].includes(file)
    || policy.documents.includes(file) || file.startsWith(policy.mediaDirectory + '/')));
  const files = new Set([...built, 'public/build-info.json', 'package.json'].filter(selected));
  for (const pattern of config.files.filter(value => !recursive.has(value))) assert.ok(files.has(pattern), 'Configured desktop input is not generated by the reviewed build: ' + pattern);
  for (const file of ['LICENSE', 'NOTICE', 'docs/THIRD_PARTY.md', 'docs/sbom.cdx.json', 'package.json', 'public/build-info.json']) assert.ok(files.has(file), 'Missing required desktop release input ' + file);
  const source = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  // build.mjs deliberately projects these fields; electron-builder removes its
  // generated scripts and applies only the reviewed main entry metadata.
  assert.deepEqual(config.extraMetadata, { main: 'desktop/main.mjs' });
  assert.notEqual(config.removePackageScripts, false, 'Revalidate generated package scripts policy');
  const packageInfo = Object.fromEntries(['name', 'version', 'description', 'author', 'homepage', 'license', 'engines'].map(key => [key, source[key]]));
  Object.assign(packageInfo, { type: 'module', main: 'desktop/main.mjs' });
  return { files, packageInfo };
}

/** Inspect actual installed/extracted archive bytes against this checkout without launching the application. */
export async function verifyDesktopArchive(archivePath) {
  archivePath = path.resolve(archivePath);
  const stat = await lstat(archivePath);
  const canonical = await realpath(archivePath);
  assert.ok(stat.isFile() && !stat.isSymbolicLink() && stat.nlink === 1 &&
    (process.platform === 'win32' ? canonical.toLowerCase() === archivePath.toLowerCase() : canonical === archivePath), 'ASAR must be an ordinary unredirected file');
  const expected = await desktopArchiveInputs();
  const expectedBuildInfo = { ...await sharedBuildInfo(root), mode: 'desktop-web' };
  const raw = asar.getRawHeader(archivePath);
  let files = 0;
  let sourceMatches = 0;
  let totalBytes = 0;
  const packagedFiles = new Set();
  async function inspect(entries, prefix = '') {
    for (const [name, entry] of Object.entries(entries)) {
      assert.ok(!name.includes('/') && !name.includes('\\') && name !== '..' && name !== '.', 'Unsafe ASAR entry');
      const relative = prefix ? `${prefix}/${name}` : name;
      if (entry.files) { await inspect(entry.files, relative); continue; }
      assert.ok(!entry.link, `Unexpected linked ASAR entry ${relative}`);
      if (entry.unpacked) {
        assert.ok(BUNDLED_SKILL_FILES.includes(relative), `Unexpected unpacked ASAR entry ${relative}`);
        const physical = path.join(`${archivePath}.unpacked`, relative);
        const resolved = await realpath(physical);
        const samePath = process.platform === 'win32' ? resolved.toLowerCase() === physical.toLowerCase() : resolved === physical;
        const stat = await lstat(physical);
        assert.ok(samePath && stat.isFile() && !stat.isSymbolicLink() && stat.nlink === 1, `Unsafe unpacked skill resource ${relative}`);
      } else {
        assert.ok(!BUNDLED_SKILL_FILES.includes(relative), `Skill resource must be a physical unpacked file ${relative}`);
      }
      assert.equal(entry.integrity?.algorithm, 'SHA256', `Missing file integrity ${relative}`);
      const bytes = asar.extractFile(archivePath, path.normalize(relative));
      assert.equal(bytes.length, entry.size, `ASAR size mismatch ${relative}`);
      assert.equal(sha256(bytes), entry.integrity.hash, `ASAR file hash mismatch ${relative}`);
      const blockSize = entry.integrity.blockSize;
      assert.ok(Number.isSafeInteger(blockSize) && blockSize > 0);
      const blocks = [];
      for (let offset = 0; offset < bytes.length; offset += blockSize) blocks.push(sha256(bytes.subarray(offset, offset + blockSize)));
      // ASAR represents an empty file with the hash of its empty block.
      if (bytes.length === 0) blocks.push(sha256(bytes));
      assert.deepEqual(entry.integrity.blocks, blocks, `ASAR block hash mismatch ${relative}`);
      assert.ok(expected.files.has(relative), `Unexpected bundled file ${relative}`);
      if (relative === 'public/build-info.json') {
        assert.deepEqual(JSON.parse(bytes.toString('utf8')), expectedBuildInfo, 'Generated shared build identity differs from source');
      } else if (relative === 'package.json') {
        assert.deepEqual(JSON.parse(bytes.toString('utf8')), expected.packageInfo, 'Generated package metadata differs from the reviewed build');
      } else {
        assert.equal(sha256(await readFile(path.join(root, relative))), sha256(bytes), 'Bundled source differs from source ' + relative);
        sourceMatches++;
      }
      packagedFiles.add(relative);
      files++;
      totalBytes += bytes.length;
    }
  }
  await inspect(raw.header.files);
  for (const required of expected.files) assert.ok(packagedFiles.has(required), 'Missing expected bundled file ' + required);
  assert.equal(packagedFiles.size, expected.files.size, 'Packaged file set differs from the reviewed build');
  return { headerSha256: sha256(raw.headerString), files, sourceMatches, totalBytes, buildInfo: expectedBuildInfo };
}

export async function verifyDesktopFuses(executable) {
  const config = JSON.parse(await readFile(path.join(root, 'desktop/electron-builder.json'), 'utf8'));
  const fuseWire = await getCurrentFuseWire(executable);
  assert.equal(fuseWire.version, '1');
  const checked = {};
  for (const [name, enabled] of Object.entries(config.electronFuses)) {
    const enumName = name[0].toUpperCase() + name.slice(1);
    assert.ok(Object.hasOwn(FuseV1Options, enumName), 'Unsupported fuse ' + name);
    assert.equal(fuseWire[FuseV1Options[enumName]], enabled ? 49 : 48, 'Unexpected fuse ' + name);
    checked[name] = enabled;
  }
  return checked;
}

export async function verifyWindowsPackage(executable) {
  const packageInfo = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const config = JSON.parse(await readFile(path.join(root, 'desktop/electron-builder.json'), 'utf8'));
  const binary = await readFile(executable);
  const resources = resedit.NtExecutableResource.from(resedit.NtExecutable.from(binary));
  const info = resedit.Resource.VersionInfo.fromEntries(resources.entries)[0];
  assert.ok(info, 'Windows version resource is missing');
  const metadata = info.getStringValues(info.getAllLanguagesForStringValues()[0]);
  assert.equal(metadata.ProductName, config.productName);
  assert.equal(metadata.FileDescription, config.productName);
  assert.equal(metadata.FileVersion, packageInfo.version);
  assert.equal(metadata.ProductVersion, `${packageInfo.version}.0`);
  assert.equal(metadata.InternalName, 'electron.exe', 'Windows runtime identity must be preserved');
  assert.equal(metadata.OriginalFilename, 'electron.exe', 'Windows runtime identity must be preserved');
  const iconGroups = resedit.Resource.IconGroupEntry.fromEntries(resources.entries);
  assert.ok(iconGroups.length, 'Windows app icon is missing');
  const expectedIcon = resedit.Data.IconFile.from(await readFile(path.join(root, 'desktop/resources/icon.ico')));
  const iconHash = item => sha256(Buffer.from(item.isRaw() ? item.bin : item.generate()));
  assert.deepEqual(iconGroups[0].getIconItemsFromEntries(resources.entries).map(iconHash), expectedIcon.icons.map(item => iconHash(item.data)), 'Windows executable icon differs from source');

  const checkedFuses = await verifyDesktopFuses(executable);

  const archivePath = path.join(path.dirname(executable), 'resources', 'app.asar');
  const raw = asar.getRawHeader(archivePath);
  const integrityResource = resources.entries.find(entry => entry.type === 'INTEGRITY' && entry.id === 'ELECTRONASAR');
  assert.ok(integrityResource, 'Embedded ASAR integrity resource is missing');
  const integrity = JSON.parse(Buffer.from(integrityResource.bin).toString('utf8'));
  assert.equal(integrity.length, 1);
  assert.equal(integrity[0].file.replaceAll('\\', '/'), 'resources/app.asar');
  assert.equal(integrity[0].alg, 'SHA256');
  const headerSha256 = sha256(raw.headerString);
  assert.equal(integrity[0].value, headerSha256, 'ASAR header does not match executable resource');

  const archive = await verifyDesktopArchive(archivePath);
  const thirdPartyNotices = await verifyThirdPartyNotices(path.dirname(executable));
  return { ok: true, thirdPartyNotices, executable: path.resolve(executable), metadata, iconFramesMatched: expectedIcon.icons.length, fuses: checkedFuses, asar: archive, executableSha256: sha256(binary) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const executable = path.resolve(process.argv[2] || path.join(root, 'release/win-unpacked/OpenAster.exe'));
  console.log(JSON.stringify(await verifyWindowsPackage(executable), null, 2));
}
