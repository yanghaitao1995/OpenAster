"""Export the existing original SVG mark as an opaque iOS AppIcon.

Developer-only Pillow dependency; normal native sync consumes the checked-in PNG.
The system applies its own icon shape, so this export fills the square background.
"""
import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import re
import stat
import xml.etree.ElementTree as ET
from PIL import Image, ImageChops, ImageDraw

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Verify generated bytes without writing')
parser.add_argument('--replace-generated', action='store_true', help='Replace only bytes identified by the existing manifest')
args = parser.parse_args()
if args.check and args.replace_generated:
    parser.error('Choose check or replacement, not both')
root = Path(__file__).absolute().parent.parent
if root.resolve() != root:
    raise ValueError('Project path must be canonical')
output = root / 'mobile' / 'resources'
png_path = output / 'ios-icon-1024.png'
manifest_path = output / 'ios-icon.json'
source_path = root / 'public' / 'icon.svg'


def checked(path, *, missing=False):
    for parent in [path, *path.parents]:
        if parent == root.parent:
            break
        if parent.is_symlink() or (hasattr(parent, 'is_junction') and parent.is_junction()):
            raise ValueError('Icon paths must not traverse links')
    try:
        info = path.stat()
    except FileNotFoundError:
        if missing:
            return None
        raise
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise ValueError('Icon input/output must be a regular single-link file')
    return path.read_bytes()


digest = lambda content: hashlib.sha256(content).hexdigest()
source = checked(source_path)
if b'<!DOCTYPE' in source or b'<!ENTITY' in source:
    raise ValueError('External SVG declarations are not supported')
svg = ET.fromstring(source)
ns = '{http://www.w3.org/2000/svg}'
if svg.tag != ns + 'svg' or svg.attrib != {'viewBox': '0 0 64 64'} or [node.tag for node in svg] != [ns + 'rect', ns + 'path']:
    raise ValueError('Review the exporter before changing the SVG structure')
background, mark = list(svg)
if set(background.attrib) != {'width', 'height', 'rx', 'fill'} or background.attrib['width'] != '64' or background.attrib['height'] != '64':
    raise ValueError('Unsupported SVG background')
if set(mark.attrib) != {'d', 'fill', 'fill-rule'} or mark.attrib['fill-rule'] != 'evenodd':
    raise ValueError('Unsupported SVG mark')
geometry = re.fullmatch(r'M([0-9. ]+)Z M([0-9. ]+)Z', mark.attrib['d'])
if geometry is None or any(re.fullmatch(r'#[0-9a-fA-F]{6}', item.attrib['fill']) is None for item in [background, mark]):
    raise ValueError('Unsupported SVG geometry or palette')
radius = float(background.attrib['rx'])
polygons = [[float(value) for value in contour.split()] for contour in geometry.groups()]
if not math.isfinite(radius) or not 0 < radius <= 32 or any(len(points) < 6 or len(points) > 128 or len(points) % 2 or any(not math.isfinite(v) or not 0 <= v <= 64 for v in points) for points in polygons):
    raise ValueError('Unsupported SVG coordinates')
scale = 32
image = Image.new('RGB', (64 * scale, 64 * scale), background.attrib['fill'])
mask = Image.new('1', image.size)
for coordinates in polygons:
    contour = Image.new('1', image.size)
    ImageDraw.Draw(contour).polygon([(x * scale, y * scale) for x, y in zip(coordinates[::2], coordinates[1::2])], fill=1)
    mask = ImageChops.logical_xor(mask, contour)
image.paste(mark.attrib['fill'], (0, 0), mask)
icon = image.resize((1024, 1024), Image.Resampling.LANCZOS)
buffer = io.BytesIO()
icon.save(buffer, format='PNG')
png = buffer.getvalue()
assert icon.mode == 'RGB' and png[25] == 2
manifest = {
    'version': 1,
    'source': {'file': 'public/icon.svg', 'sha256': digest(source)},
    'asset': {'file': 'mobile/resources/ios-icon-1024.png', 'sha256': digest(png), 'bytes': len(png), 'width': 1024, 'height': 1024, 'colorType': 2},
    'generator': 'mobile/generate-ios-icon.py',
    'appearance': 'Original project mark on its opaque square background; native system supplies the icon shape.',
}
manifest_bytes = (json.dumps(manifest, indent=2, ensure_ascii=False) + '\n').encode('utf-8')
old_png = checked(png_path, missing=True)
old_manifest = checked(manifest_path, missing=True)
if args.check:
    if old_png != png or old_manifest != manifest_bytes:
        raise ValueError('Generated iOS icon or manifest is stale')
else:
    if old_png is not None or old_manifest is not None:
        if old_png == png and old_manifest == manifest_bytes:
            print(json.dumps({'status': 'unchanged', **manifest['asset']}))
            raise SystemExit(0)
        if not args.replace_generated or old_png is None or old_manifest is None:
            raise ValueError('Review existing files; replacement requires --replace-generated and a valid manifest')
        previous = json.loads(old_manifest)
        if previous.get('version') != 1 or previous.get('asset', {}).get('file') != manifest['asset']['file'] or previous['asset'].get('sha256') != digest(old_png):
            raise ValueError('Existing icon does not match its ownership manifest')
    if not output.exists():
        output.mkdir()
    for destination, before, after in [(png_path, old_png, png), (manifest_path, old_manifest, manifest_bytes)]:
        if checked(destination, missing=True) != before:
            raise ValueError('Icon destination changed before writing')
        with destination.open('xb' if before is None else 'r+b') as stream:
            if before is not None and stream.read() != before:
                raise ValueError('Icon destination changed while opening')
            stream.seek(0)
            stream.write(after)
            stream.truncate()
    assert checked(png_path) == png and checked(manifest_path) == manifest_bytes
print(json.dumps({'status': 'verified' if args.check else 'generated', **manifest['asset']}))
