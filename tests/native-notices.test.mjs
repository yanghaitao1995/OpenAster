import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import { decodeNoticeEntities, parseChromiumNotices, readChromiumNoticeInventory } from '../scripts/native-notices.mjs';

const digest = (value) => createHash('sha256').update(value).digest('hex');
const product = (text = 'Copyright (C) Example.\r\nAll rights reserved.\r\n', title = 'Example', homepage = 'https://example.invalid/') =>
  `<div class="product">\r\n<span class="title">${title}</span>\r\n${homepage === null ? '' : `<span class="homepage"><a href="${homepage}">homepage</a></span>\r\n`}<label class="show" tabindex="0"><input type="checkbox" hidden></label>\r\n<div class="license">\r\n<pre>${text}</pre>\r\n</div>\r\n</div>`;
const document = (...records) => `<!-- Generated by licenses.py; do not edit. --><!doctype html>\r\n<html><head><meta charset="utf-8"><title>Credits</title></head><body>\r\n<span class="page-title">Credits</span>\r\n<div><!-- Chromium <3s the following projects -->\r\n${records.join('\r\n')}\r\n</div>\r\n`;

test('preserves source text, CRLF, punctuation and byte-bound records in generated structure', () => {
  const raw = '\r\n  &quot;许可&quot; &amp; &lt;tag&gt; &#x27; &#169; &#x1F600; &amp;quot;\r\n\t  ';
  const source = Buffer.from(document(product(raw, 'A &amp; B', 'https://example.invalid/?a=1&amp;b=2'), product('Other\n', 'A &amp; B', null)));
  const inventory = parseChromiumNotices(source, { sourcePath: 'fixture.html' });
  assert.equal(inventory.recordCount, 2);
  assert.equal(inventory.source.sha256, digest(source));
  assert.equal(inventory.source.byteLength, source.length);
  assert.equal(inventory.source.path, 'fixture.html');
  assert.equal(inventory.records[0].title, 'A & B');
  assert.equal(inventory.records[0].homepage, 'https://example.invalid/?a=1&b=2');
  assert.equal(inventory.records[0].licenseText, '\r\n  "许可" & <tag> \' © 😀 &quot;\r\n\t  ');
  assert.equal(inventory.records[1].homepage, null);
  assert.deepEqual(inventory.records.map((record) => record.index), [1, 2]);
  for (const record of inventory.records) {
    const rawRecord = source.subarray(record.source.startByte, record.source.endByte);
    assert.equal(record.source.sha256, digest(rawRecord));
    assert.equal(record.licenseTextSha256, digest(record.licenseText));
    assert.ok(rawRecord.toString().startsWith('<div class="product">'));
    assert.equal(parseChromiumNotices(rawRecord).records[0].licenseText, record.licenseText);
    assert.equal(Object.hasOwn(record, 'version'), false);
    assert.equal(Object.hasOwn(record, 'spdx'), false);
  }
});

test('decodes entities once and refuses unknown, ambiguous or destructive references', () => {
  assert.equal(decodeNoticeEntities('&apos;&nbsp;&quot;&lt;&gt;&amp;&#39;&#X41;'), '\'\u00a0"<>&\'A');
  assert.equal(decodeNoticeEntities('R & D &amp;madeup;'), 'R & D &madeup;');
  for (const entity of ['&madeup;', '&copy;', '&amp', '&#xZZ;', '&#0;', '&#xD800;', '&#x110000;', '&#128;']) {
    assert.throws(() => parseChromiumNotices(product(entity)), /entity/);
  }
});

test('retains homepage values as source text without asserting they are valid URLs', () => {
  const inventory = parseChromiumNotices(product('License', 'Example', 'This is the canonical repository.'));
  assert.equal(inventory.records[0].homepage, 'This is the canonical repository.');
});

test('rejects missing, duplicate, empty and structurally unrecognized records', () => {
  const valid = product();
  const invalid = [
    '',
    valid.replace('<span class="title">Example</span>', ''),
    valid.replace('<span class="title">Example</span>', '<span class="title"></span>'),
    valid.replace('<span class="title">Example</span>', '<span class="title">Example</span><span class="title">Extra</span>'),
    valid.replace(/<div class="license">[\s\S]*?<\/pre>\r\n<\/div>/, ''),
    product(' \r\n\t'),
    valid.replace('</pre>', ''),
    valid.slice(0, -6),
    valid.replace('<pre>', '<pre><b>'),
    valid.replace('<pre>', '<pre><!-- omit -->'),
    valid.replace('class="license"', 'class="unrecognized-license"'),
    valid.replace('</pre>', '</pre><pre>Extra license</pre>'),
    valid.replace('href="https://example.invalid/"', ''),
    valid.replace('href="https://example.invalid/"', 'href=""'),
    valid.replace('class="product"', 'class="product" class="product"'),
    valid.replace('class="product"', 'class="product title"'),
    valid.replace('</label>', '<span>Extra content</span></label>'),
    valid.replace('<input type="checkbox" hidden>', '<input type="text">'),
    valid.replace('</div>\r\n</div>', '</div><span>Unrecognized field</span></div>'),
    document(valid, product().replace('class="product"', 'class="unknown-record"')),
    `${document(valid)}<pre>Unbound license</pre>`,
    `${document(valid)}<div class="unknown-record">Other notice</div>`,
    `${document(valid)}<script>throw new Error("must never run")</script>`,
  ];
  for (const source of invalid) assert.throws(() => parseChromiumNotices(source), /Chromium notices:/, source.slice(0, 150));
});

test('rejects invalid UTF-8 and unpaired Unicode without replacement characters', () => {
  assert.throws(() => parseChromiumNotices(Buffer.from([0xc3, 0x28])), /UTF-8/);
  assert.throws(() => parseChromiumNotices(product('\ud800')), /Unicode/);
  assert.throws(() => parseChromiumNotices(product('\0')), /NUL/);
  assert.throws(() => parseChromiumNotices({}), TypeError);
});

test('extracts every record of the existing packaged Chromium notice file when available', async (t) => {
  const path = new URL('../release/command-outcome/win-unpacked/LICENSES.chromium.html', import.meta.url);
  let source;
  try {
    source = await readFile(path);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    t.skip('Existing release artifact is not part of the source checkout');
    return;
  }
  const inventory = await readChromiumNoticeInventory(path);
  const html = source.toString('utf8');
  assert.equal(inventory.recordCount, [...html.matchAll(/<div class="product">/g)].length);
  assert.equal(inventory.recordCount, [...html.matchAll(/<pre>/g)].length);
  assert.ok(inventory.recordCount > 0);
  assert.equal(inventory.source.sha256, digest(source));
  assert.equal(inventory.records[0].title, '2-dim General Purpose FFT (Fast Fourier/Cosine/Sine Transform) Package');
  assert.equal(inventory.records[0].licenseText, 'Copyright(C) 1997,2001 Takuya OOURA (email: ooura@kurims.kyoto-u.ac.jp).\r\nYou may use, copy, modify this code for any purpose and \r\nwithout fee. You may distribute this ORIGINAL package.\r\n');
  for (const record of inventory.records) {
    const raw = source.subarray(record.source.startByte, record.source.endByte).toString('utf8');
    const expected = /<pre>([\s\S]*?)<\/pre>/.exec(raw)[1]
      .replace(/&quot;|&#x27;|&lt;|&gt;|&amp;/g, (entity) => ({ '&quot;': '"', '&#x27;': "'", '&lt;': '<', '&gt;': '>', '&amp;': '&' })[entity]);
    assert.equal(record.licenseText, expected, record.title);
  }
});
